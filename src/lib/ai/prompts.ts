export function documentPrompt({ kind, topic, grade, subject, count }: DocumentRequest) {
  const task = documentTask[kind].map((line) => line.replace("{count}", String(count)));
  return [`Предмет: ${subjectPromptNames[subject]}. Тема: «${topic}», ${grade} класс.`, ...task].join("\n");
}

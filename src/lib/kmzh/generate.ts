/** Образец стиля и объёма: sample.json без полей учителя */
const teacherFields = ["teacher_name", "date", "grade", "topic", "textbook_ref"];
const SAMPLE = Object.fromEntries(Object.entries(sample).filter(([key]) => !teacherFields.includes(key)));

export function generateKmzh(req: DocumentRequest): Promise<KmzhAi> {
  const kazakh = req.language === "kk";
  const prompt = [
    "Ты — опытный учитель, составляешь ҚМЖ (қысқа мерзімді жоспар) по обновлённой программе РК. Урок 45 минут, 8 этапов.",
    "",
    "ДАННЫЕ УЧИТЕЛЯ",
    `Пән: ${subjectPromptNames[req.subject]}. Сынып: ${req.grade}. Тақырып: «${req.topic}».`,
    req.section ? `Бөлім: ${req.section} — в поле section повтори без изменений.` : "Бөлім не указан — предложи раздел учебной программы в поле section.",
    req.objective
      ? `Оқу мақсаты: ${req.objective} — в поле learning_objective повтори без изменений.`
      : "Оқу мақсаты не указан — предложи в learning_objective код и текст цели по программе РК (формат «8.3.2.17 – …»). Учитель его проверит.",
    req.textbook ? `Оқулық: ${req.textbook}.` : "Оқулық не указан — не пиши номера параграфов, страниц и рисунков.",
    req.value ? `Апта құндылығы: ${req.value} — используй её в task2.` : "",
    `Тип урока: ${lessonTypePrompt[req.lessonType]}`,
    planTypePrompt[req.planType],
    "",
    kazakh
      ? "Язык ҚМЖ — казахский литературный."
      : "Язык ҚМЖ — русский: все тексты по-русски, заголовки блоков тоже («Ожидаемый ответ:», «Дифференциация:», «Домашнее задание:»), названия приёмов — по-русски.",
    "",
    "ПРАВИЛА",
    RULES,
    req.taskCount === 4 ? FOUR_TASKS : "",
    "ОБРАЗЕЦ — стиль и объём для другой темы. Содержание НЕ копируй, пиши по своей теме:",
    JSON.stringify(SAMPLE),
    "",
    "Ответь только JSON по схеме. Перед ответом проверь все вычисления и баллы.",
  ]
    .filter((line) => line !== "")
    .join("\n");
  // При 4 заданиях схема требует task4 и проверяет баллы 3 + 4 + 3
  const schema = req.taskCount === 4 ? kmzhAi4Schema : kmzhAiSchema;
  return generateJson(schema, systemPrompt(req.language, req.grade), prompt);
}
